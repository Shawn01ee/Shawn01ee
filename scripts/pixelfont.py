def pixel_text(text, x, y, s, gap=1):
    """Return (path_d, width) drawing `text` with pixel size `s`, top-left at (x, y)."""
    parts = []
    cx = x
    for ch in text.upper():
        rows = GLYPHS[ch]
        for r, row in enumerate(rows):
            for c, bit in enumerate(row):
                if bit == "#":
                    parts.append(f"M{cx + c * s:g} {y + r * s:g}h{s:g}v{s:g}h-{s:g}z")
        cx += (5 + gap) * s
    width = cx - x - gap * s if text else 0
    return "".join(parts), width


def pixel_width(text, s, gap=1):
    return len(text) * (5 + gap) * s - gap * s if text else 0


def grid_art(rows, palette, x, y, u):
    """Draw character-grid art. Returns {color: path_d}."""
    paths = {}
    for r, row in enumerate(rows):
        for c, key in enumerate(row):
            if key in palette:
                color = palette[key]
                paths.setdefault(color, []).append(f"M{x + c * u:g} {y + r * u:g}h{u:g}v{u:g}h-{u:g}z")
    return {color: "".join(d) for color, d in paths.items()}


def esc(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


